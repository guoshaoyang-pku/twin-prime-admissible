def parse(k, d, s):
    nums = [int(x) for x in s.split(",")]
    assert len(nums) == k, f"k={k} d={d}: got {len(nums)} elements, expected {k}"
    assert min(nums) == 0, f"k={k} d={d}: min is {min(nums)}"
    assert max(nums) == d, f"k={k} d={d}: max is {max(nums)}"
    assert len(set(nums)) == k, f"k={k} d={d}: duplicates present"
    return sorted(nums)

def fmt(nums):
    return "[" + ", ".join(str(x) for x in nums) + "]"

